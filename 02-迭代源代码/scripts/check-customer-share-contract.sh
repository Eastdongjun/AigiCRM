#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTROLLER="$ROOT/aigicrm-backend/src/main/java/com/aigicrm/module/customer/controller/CustomerController.java"
PAGE="$ROOT/aigicrm-miniprogram/pages/customer/share/index.js"
WXML="$ROOT/aigicrm-miniprogram/pages/customer/share/index.wxml"
WXSS="$ROOT/aigicrm-miniprogram/pages/customer/share/index.wxss"
MANIFEST="$ROOT/docs/unified-feature-manifest.md"

grep -q "@GetMapping(\"/{id}/shares\")" "$CONTROLLER"
grep -B1 -A2 -q "@GetMapping(\"/{id}/shares\")" "$CONTROLLER"
grep -B1 -A2 -q "@PostMapping(\"/{id}/shares\")" "$CONTROLLER"
grep -B1 -A2 -q "@DeleteMapping(\"/{id}/shares/{userId}\")" "$CONTROLLER"
grep -q "hasAuthority('customer:view')" "$CONTROLLER"
grep -q "hasAuthority('customer:edit')" "$CONTROLLER"
grep -q "hasPermission('customer:view')" "$PAGE"
grep -q "hasPermission('customer:edit')" "$PAGE"
grep -q "buildShareView" "$PAGE"
grep -q "applyState(patch)" "$PAGE"
grep -q "userNameText" "$PAGE"
grep -q "createdAtText" "$PAGE"
grep -q "shareView.shares" "$WXML"
grep -q "shareView.users" "$WXML"
grep -q "shareView.showEmpty" "$WXML"
grep -q "shareView.showForm" "$WXML"
grep -q "submitLoading" "$PAGE"
grep -q "submitText" "$PAGE"
grep -q "cancelText" "$PAGE"
grep -q "cancelDisabled" "$PAGE"
# 【D24 锚点重钉 2026-10-05】返回兜底逻辑(栈深判断 getCurrentPages)收敛到 pages/customer/shared.js 的
# navigateBackWithFallback,本页改为引用共享函数;意图不变:直达分享页时返回不失灵
grep -q "navigateBackWithFallback" "$PAGE"
grep -q "getCurrentPages" "$ROOT/aigicrm-miniprogram/pages/customer/shared.js"
grep -q "shareView.submitLoading" "$WXML"
grep -q "shareView.submitText" "$WXML"
grep -q "shareView.cancelDisabled" "$WXML"
grep -q "shareView.cancelText" "$WXML"
! grep -Eq "item\\.(sharedToUserName|userName|createdAt|createTime|realName|username) \\|\\||shares\\.length|users\\.length|!loading &&|canEdit && users" "$WXML"
! grep -Fq "{{saving}}" "$WXML"
grep -q 'class="share-revoke-btn"' "$WXML"
grep -q 'class="share-submit-btn"' "$WXML"
grep -q 'class="share-actions"' "$WXML"
grep -q 'class="share-cancel-btn"' "$WXML"
grep -q 'class="share-top-cancel"' "$WXML"
grep -q '.share-revoke-btn' "$WXSS"
grep -q '.share-submit-btn' "$WXSS"
grep -q '.share-cancel-btn' "$WXSS"
grep -q '.share-top-cancel' "$WXSS"
grep -q 'height:50rpx' "$WXSS"
# 【2026-09-29 锚点重钉】manifest 中文化(2b80b62e)后英文 add/revoke 断连; 重钉为分享行中文语义(新增/撤销走 customer:edit 门控)
grep -q "customer.share.*新增/撤销.*customer:edit" "$MANIFEST"

echo "PASS: customer share read/mutation permissions match backend, mobile page, and manifest."
# 【2026-11-07 纪律门禁T1】显式判定出口: 判定只认退出码, 不靠末命令隐式传播(check-discipline-gates §2)
exit 0
