# -*- coding: utf-8 -*-
"""【治本⑤ 2026-11-11】biz_folder_type_default 去重清理——本地计算+按主键生成朴素 SQL。

背景: 同键多行与词内重复(11-10 双写期竞态产物)。SQL 端三轮翻车实证(临时表跨 collation/
同表子查询 1093/JSON_TABLE 相关子查询丢词), Java 迁移被独立 flyway 容器架构堵死——
故由本脚本读全表快照、程序内完成分组/并集/去重, 只生成**按主键**的 UPDATE/DELETE 语句,
任意 mysql 通道执行皆确定性。幂等: 无变化时生成空集。

用法:
  mysql -N -e "SELECT id,folder_type,object_type,IFNULL(folder_id,'N'),subject_type,subject_id,perms FROM biz_folder_type_default ORDER BY id" 的输出 | 本脚本 > dedup.sql
"""
import sys


def main():
    groups = {}   # key -> [(id, perms)]
    order = []
    for line in sys.stdin:
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 7:
            continue
        rid, ftype, otype, fid, stype, sid, perms = parts
        key = (ftype, otype, fid, stype, sid)
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append((int(rid), perms))
    ups, dels = [], []
    for key in order:
        rows = groups[key]          # 输入已 ORDER BY id ⇒ 首行即最小 id
        keep_id, _ = rows[0]
        words = set()
        for _, perms in rows:
            if perms:
                for w in perms.split(","):
                    w = w.strip()
                    if w:
                        words.add(w)
        merged = ",".join(sorted(words))
        if rows[0][1] != merged:
            ups.append(f"UPDATE biz_folder_type_default SET perms = '{merged}' WHERE id = {keep_id};")
        for rid, _ in rows[1:]:
            dels.append(f"DELETE FROM biz_folder_type_default WHERE id = {rid};")
    print("-- auto-generated by fix-file-perm-dedup.py (幂等, 仅主键定位)")
    for s in ups:
        print(s)
    for s in dels:
        print(s)
    print(f"-- updated={len(ups)} deleted={len(dels)}")


if __name__ == "__main__":
    main()
