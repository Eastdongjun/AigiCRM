#!/usr/bin/env bash
# Keep public-sea import/config mutations out of the mobile release, while allowing backend-guarded row delete.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
API="$ROOT/aigicrm-miniprogram/api/sea.js"
PAGE="$ROOT/aigicrm-miniprogram/pages/sea/index.js"
WXML="$ROOT/aigicrm-miniprogram/pages/sea/index.wxml"
WXSS="$ROOT/aigicrm-miniprogram/pages/sea/index.wxss"
MANIFEST="$ROOT/docs/unified-feature-manifest.md"
AUTOMATOR_PACKAGE="$ROOT/scripts/miniprogram/package.json"
AUTOMATOR_SCRIPT="$ROOT/scripts/miniprogram/verify-sea-center.mjs"

fail() { echo "FAIL: $*" >&2; exit 1; }

for token in importSea importPool createSea updateSea deletePool saveSeaConfig; do
  ! grep -Fq "$token" "$API" || fail "mobile sea API exposes forbidden $token"
  ! grep -Fq "$token" "$PAGE" || fail "mobile sea page exposes forbidden $token"
done
for token in '导入' '配置公海' '保存配置'; do
  ! grep -Fq "$token" "$WXML" || fail "mobile sea UI exposes forbidden $token"
done
grep -Fq "url: '/api/sea/configs/visible'" "$API" || fail 'visible sea config API disappeared'
grep -Fq 'Boolean(item.canClaim)' "$PAGE" || fail 'backend canClaim flag is not consumed'
grep -Fq 'Boolean(item.canEdit)' "$PAGE" || fail 'backend canEdit flag is not consumed'
grep -Fq 'Boolean(item.canDelete)' "$PAGE" || fail 'backend canDelete flag is not consumed'
grep -Fq 'canClaimNow: available && canClaim' "$PAGE" || fail 'mobile sea claim visibility must normalize available plus backend canClaim'
grep -Fq 'canDeleteNow: available && canDelete' "$PAGE" || fail 'mobile sea delete visibility must normalize available plus backend canDelete'
grep -Fq 'canShowActions:' "$PAGE" || fail 'mobile sea row action visibility must be normalized before WXML'
grep -Fq 'permissionText:' "$PAGE" || fail 'mobile sea row permission copy must be normalized before WXML'
grep -Fq 'buildSeaView' "$PAGE" || fail 'mobile sea page must normalize page view state before WXML'
grep -Fq 'buildSeaRecordView' "$PAGE" || fail 'mobile sea rows must be normalized before WXML'
grep -Fq 'claimLoading' "$PAGE" || fail 'mobile sea claim loading must be normalized before WXML'
grep -Fq 'deleteLoading' "$PAGE" || fail 'mobile sea delete loading must be normalized before WXML'
grep -Fq 'buildClaimRecordView' "$PAGE" || fail 'mobile sea claim records must be normalized before WXML'
grep -Fq 'setSeaData' "$PAGE" || fail 'mobile sea page must refresh normalized view state with data changes'
grep -Fq 'refreshLoading' "$PAGE" || fail 'mobile sea page must expose normalized refresh loading state'
grep -Fq 'refreshText' "$PAGE" || fail 'mobile sea page must expose normalized refresh label'
grep -Fq 'showLoading' "$PAGE" || fail 'mobile sea page must expose normalized loading visibility'
grep -Fq 'loadingText' "$PAGE" || fail 'mobile sea page must expose normalized loading text'
grep -Fq 'seaStatusText' "$PAGE" || fail 'mobile sea list must normalize sea row status labels like PC'
grep -Fq 'seaReasonText' "$PAGE" || fail 'mobile sea list must normalize PC enter-reason labels'
grep -Fq 'claimStatusText' "$PAGE" || fail 'mobile sea claim records must normalize approval status labels like PC'
grep -Fq "PENDING_APPROVAL: '审批中'" "$PAGE" || fail 'mobile sea row status must display PC uppercase status variants'
grep -Fq "WAITING: '待审批'" "$PAGE" || fail 'mobile sea claim status must display PC waiting status variants'
grep -Fq "WAITING: '待审批'" "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.js" || fail 'mobile sea claim detail must display PC waiting status variants'
grep -Fq 'buildClaimView' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.js" || fail 'mobile sea claim detail must normalize view state before WXML'
grep -Fq 'setClaimData' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.js" || fail 'mobile sea claim detail must refresh normalized view state with data changes'
grep -Fq 'claimView.statusText' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail must display normalized status text'
grep -Fq 'claimView.reasonText' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail must display normalized reason text'
! grep -Fq 'statusLabel || status' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail WXML must not duplicate status fallback logic'
! grep -Fq 'createdAt ||' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail WXML must not duplicate created-at fallback logic'
! grep -Fq 'applicantName ||' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail WXML must not duplicate applicant fallback logic'
! grep -Fq 'approveTime ||' "$ROOT/aigicrm-miniprogram/pages/sea/claim-detail/index.wxml" || fail 'mobile sea claim detail WXML must not duplicate approve-time fallback logic'
grep -Fq 'normalizeClaimRecord' "$PAGE" || fail 'mobile sea claim records must retain PC claim record fields'
grep -Fq 'getDictData' "$PAGE" || fail 'mobile sea filters must load PC industry dictionary'
grep -Fq 'getDepts' "$PAGE" || fail 'mobile sea filters must load PC department dictionary'
grep -Fq 'applyDepts' "$PAGE" || fail 'mobile sea department tree is not flattened for picker use'
grep -Fq 'deptId: this.data.deptId || undefined' "$PAGE" || fail 'mobile sea list does not pass deptId filter like PC'
grep -Fq 'industry: this.data.industry || undefined' "$PAGE" || fail 'mobile sea list does not pass industry filter like PC'
grep -Fq 'enterReason: this.data.enterReason || undefined' "$PAGE" || fail 'mobile sea list does not pass enter-reason filter like PC'
grep -Fq 'chooseIndustry' "$PAGE" || fail 'mobile sea industry filter handler is missing'
grep -Fq 'chooseDept' "$PAGE" || fail 'mobile sea department filter handler is missing'
grep -Fq 'chooseEnterReason' "$PAGE" || fail 'mobile sea enter-reason filter handler is missing'
grep -Fq 'item.statusText' "$WXML" || fail 'mobile sea UI must display normalized status labels'
grep -Fq '全部部门' "$PAGE" || fail 'mobile sea UI has no department filter'
grep -Fq '全部行业' "$PAGE" || fail 'mobile sea UI has no industry filter'
grep -Fq '全部原因' "$PAGE" || fail 'mobile sea UI has no enter-reason filter'
grep -Fq "if (!item || !item.canClaimNow) return" "$PAGE" \
  || fail 'mobile sea claim action is not guarded by backend canClaim'
grep -Fq 'deleteSeaPool' "$API" || fail 'mobile sea delete API is missing'
grep -Fq "url: '/api/sea/pool/' + id" "$API" || fail 'mobile sea delete endpoint is stale'
grep -Fq 'deleteSeaCustomer' "$PAGE" || fail 'mobile sea delete action is missing'
grep -Fq "if (!item || !item.canDeleteNow) return" "$PAGE" \
  || fail 'mobile sea delete action is not guarded by backend canDelete and available status'
grep -Fq 'deleteSeaPool(item.id)' "$PAGE" || fail 'mobile sea delete action does not call delete API'
grep -Fq 'editSeaCustomer' "$PAGE" || fail 'mobile sea edit action disappeared'
grep -Fq 'openCustomer' "$PAGE" || fail 'mobile sea customer archive action disappeared'
grep -Fq '/pages/customer/detail/index?id=${item.customerId}&from=sea' "$PAGE" || fail 'mobile sea customer archive route is stale'
grep -Fq '!item.canEdit' "$PAGE" || fail 'mobile sea edit action is not guarded by backend canEdit'
grep -Fq '/pages/customer/form/index?id=' "$PAGE" || fail 'mobile sea edit action does not route to customer edit form'
grep -Fq 'bindtap="claim"' "$WXML" || fail 'mobile sea claim action disappeared'
grep -Fq 'bindtap="editSeaCustomer"' "$WXML" || fail 'mobile sea edit UI disappeared'
grep -Fq 'bindtap="deleteSeaCustomer"' "$WXML" || fail 'mobile sea delete UI disappeared'
grep -Fq 'item.permissionText' "$WXML" || fail 'mobile sea UI must display normalized permission text'
grep -Fq 'item.canShowActions' "$WXML" || fail 'mobile sea actions must use normalized visibility'
grep -Fq 'item.canClaimNow' "$WXML" || fail 'mobile sea claim button must use normalized visibility'
grep -Fq 'item.canDeleteNow' "$WXML" || fail 'mobile sea delete button must use normalized visibility'
grep -Fq 'item.claimLoading' "$WXML" || fail 'mobile sea claim button must use normalized loading state'
grep -Fq 'item.deleteLoading' "$WXML" || fail 'mobile sea delete button must use normalized loading state'
! grep -Fq 'claimingId===item.id' "$WXML" || fail 'mobile sea WXML must not compare claiming id directly'
! grep -Fq 'deletingId===item.id' "$WXML" || fail 'mobile sea WXML must not compare deleting id directly'
! grep -Fq "item.status==='available'" "$WXML" || fail 'mobile sea WXML must not duplicate available status checks'
! grep -Fq "item.canClaim ? '可捞取" "$WXML" || fail 'mobile sea WXML must not concatenate permission text'
grep -Fq 'sea-search-action' "$WXML" || fail 'mobile sea search action must use compact local style'
grep -Fq 'sea-actions' "$WXML" || fail 'mobile sea row actions must use compact local action row'
grep -Fq 'sea-claim-action' "$WXML" || fail 'mobile sea claim action must use compact local style'
grep -Fq 'sea-edit-action' "$WXML" || fail 'mobile sea edit action must use compact local style'
grep -Fq 'sea-delete-action' "$WXML" || fail 'mobile sea delete action must use compact local style'
grep -Fq '.sea-actions' "$WXSS" || fail 'mobile sea compact action styles disappeared'
grep -Fq 'height:50rpx' "$WXSS" || fail 'mobile sea action buttons must stay compact'
grep -Fq '可按权限发起捞取审批' "$WXML" || fail 'mobile sea header copy still claims read-only behavior'
grep -Fq '池内待捞' "$PAGE" || fail 'mobile sea stats must show PC total pending label'
grep -Fq 'newThisMonth' "$PAGE" || fail 'mobile sea stats must show PC new-this-month metric'
grep -Fq '待审批捞取' "$PAGE" || fail 'mobile sea stats must show PC pending-approval label'
grep -Fq 'claimedThisMonth' "$PAGE" || fail 'mobile sea stats must show PC claimed-this-month metric'
grep -Fq 'seaView.statsCards' "$WXML" || fail 'mobile sea stats must render normalized stat cards'
grep -Fq 'seaView.refreshLoading' "$WXML" || fail 'mobile sea refresh button must use normalized loading state'
grep -Fq 'seaView.refreshText' "$WXML" || fail 'mobile sea refresh button must use normalized label'
grep -Fq 'seaView.showLoading' "$WXML" || fail 'mobile sea loading card must use normalized visibility'
grep -Fq 'seaView.loadingText' "$WXML" || fail 'mobile sea loading card must use normalized copy'
grep -Fq 'seaView.statusText' "$WXML" || fail 'mobile sea status picker must render normalized filter text'
grep -Fq 'seaView.deptText' "$WXML" || fail 'mobile sea department picker must render normalized filter text'
grep -Fq 'seaView.records' "$WXML" || fail 'mobile sea list must render normalized record rows'
grep -Fq 'seaView.claimRecords' "$WXML" || fail 'mobile sea claim list must render normalized claim rows'
! grep -Fq 'stats.total || 0' "$WXML" || fail 'mobile sea WXML must not compute stats fallbacks'
! grep -Fq "status==='available'" "$WXML" || fail 'mobile sea WXML must not compute status picker text'
! grep -Fq 'deptOptions[selectedDeptIndex]' "$WXML" || fail 'mobile sea WXML must not index department picker options directly'
! grep -Fq 'statusLabel ||' "$WXML" || fail 'mobile sea WXML must not duplicate status fallback logic'
! grep -Fq 'customerCode ||' "$WXML" || fail 'mobile sea WXML must not duplicate code fallback logic'
! grep -Fq 'claimRecords.length' "$WXML" || fail 'mobile sea WXML must not inspect claim record length directly'
! grep -Fq '{{loading}}' "$WXML" || fail 'mobile sea WXML must not bind raw loading state directly'
! grep -Fq "item.customerName || item.title" "$WXML" || fail 'mobile sea WXML must not duplicate claim title fallback logic'
grep -Fq 'verify:sea-center' "$AUTOMATOR_PACKAGE" || fail 'public sea DevTools automator script is not exposed'
grep -Fq 'verifySeaCenterPage' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not verify page UI'
grep -Fq "item.title === '捞取确认'" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert claim confirmation'
grep -Fq "item.title === '捞取申请已提交'" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert claim submission toast'
grep -Fq "item.title === '演示记录不可删除'" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert delete guard'
grep -Fq '待审批' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert PC claim status label'
grep -Fq 'applicantName=%E5%BC%A0%E4%B8%89' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert claim applicant navigation payload'
grep -Fq "filterState.industry === '制造业'" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert industry filter state'
grep -Fq "filterState.deptId === 21" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert department filter state'
grep -Fq "filterState.enterReason === '保护期满'" "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert enter-reason filter state'
grep -Fq '/pages/customer/detail/index?id=501&from=sea' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert customer archive navigation'
grep -Fq '/pages/customer/form/index?id=501&from=sea' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not assert edit navigation'
grep -Fq 'sea-center-actions.png' "$AUTOMATOR_SCRIPT" || fail 'public sea DevTools automator does not capture UI evidence'
grep -Fq '`sea.edit` | 公海 | 公海行编辑/客户表单 | `pages/sea/index` 至 `pages/customer/form/index?id=:id&from=sea`' "$MANIFEST" || fail 'sea edit manifest does not point to mobile customer edit route'
grep -Fq '`sea.delete` | 公海 | 公海行删除,`/api/sea/pool/{id}` | `pages/sea/index` 行删除' "$MANIFEST" || fail 'sea delete manifest does not point to mobile row delete action'
echo 'PASS: mobile public-sea high-risk boundary is aligned.'
