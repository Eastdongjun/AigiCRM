-- ============================================================
-- V21__cleanup_dead_menu_permissions.sql
-- 清理前后端零引用的废弃菜单权限点
--
-- 背景(2026-08-27 权限点引用审计):
--   审计比对生产库 sys_menu 全部 81 个启用权限码与后端 Java(@PreAuthorize/
--   hasAuthority)及前端 Vue/JS(hasPermission/router meta)实际引用, 发现 12 个
--   权限码零引用或已废弃——勾选不生效, 误导管理员。
--   其中 61「积分排行」是实际页面入口(前端 router 用 score:view 控制), 保留;
--   22「积分榜」是无前端页面的历史空壳, 一并清理。
--
-- 处理:
--   1. sys_menu.status=0 停用 12 个废弃菜单行(保留数据可回滚)
--   2. 删除 sys_role_menu 中对应绑定, 避免角色配置界面残留已停用菜单
--   3. 不做物理删除, 恢复只需 status=1 + 重新绑定
--   注意: sys_menu 表无 updated_at 列(生产实测), 故只更新 status
-- ============================================================
-- 1) 停用废弃菜单行(含积分榜空壳 22; 保留积分排行 61)
UPDATE sys_menu
SET status = 0
WHERE id IN (
        22,
        47,
        48,
        54,
        63,
        81,
        89,
        110,
        111,
        120,
        122,
        123
    )
    AND status = 1;
-- 2) 删除对应角色绑定
DELETE FROM sys_role_menu
WHERE menu_id IN (
        22,
        47,
        48,
        54,
        63,
        81,
        89,
        110,
        111,
        120,
        122,
        123
    );
